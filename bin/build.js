function useFilamentColors(styles) {
    return styles.replace(/#([0-9a-f]{8}|[0-9a-f]{6}|[0-9a-f]{3})\b/gi, (match, hex) => {
        hex = hex.toLowerCase()

        if (hex.length === 3) {
            hex = [...hex].map((digit) => digit + digit).join('')
        }

        const color = filamentColors[hex.slice(0, 6)]

        if (!color) {
            return match
        }

        if (hex.length === 6) {
            return `var(--${color})`
        }

        const opacity = Math.round((parseInt(hex.slice(6), 16) / 255) * 100)

        return `color-mix(in srgb,var(--${color}) ${opacity}%,transparent)`
    })
}

// Uppy ships its stylesheet precompiled. The application's theme imports the
// package's CSS from `vendor/`, where `node_modules/@uppy` does not exist, so
// a copy that matches the bundled scripts is kept in the package.
function copyUppyStyles() {
    const require = createRequire(import.meta.url)
    const { version } = require('@uppy/dashboard/package.json')
    const styles = readFileSync(
        require.resolve('@uppy/dashboard/css/style.min.css'),
        'utf8',
    ).replace(/^@charset "UTF-8";/, '')

    writeFileSync(
        'resources/css/uppy.css',
        `/* Generated by bin/build.js from @uppy/dashboard ${version}. Do not edit. */\n${useFilamentColors(styles)}\n`,
    )
}

copyUppyStyles()
removeStaleChunks()

if (isDev) {
    const context = await esbuild.context(options)

    await context.watch()

    console.log(`Watching ${options.entryPoints['components/fluppy']}`)
} else {
    await esbuild.build(options)

    console.log(`Built ${outdir}`)
}
