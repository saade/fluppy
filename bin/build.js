import esbuild from 'esbuild'
import { readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'

const isDev = process.argv.includes('--dev')

const outdir = 'resources/dist'

const options = {
    entryPoints: { 'components/fluppy': 'resources/js/index.js' },
    outdir,
    // Anything imported with `import()` becomes a file of its own next to
    // `components/`, which the service provider registers to load on request.
    splitting: true,
    chunkNames: 'fluppy-[name]-[hash]',
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: ['es2020'],
    treeShaking: true,
    minify: !isDev,
    sourcemap: isDev ? 'inline' : false,
    define: {
        'process.env.NODE_ENV': isDev ? `'development'` : `'production'`,
    },
}

// Chunk names carry a hash, so the ones from an earlier build would pile up.
function removeStaleChunks() {
    for (const file of readdirSync(outdir)) {
        if (file.endsWith('.js')) {
            rmSync(`${outdir}/${file}`)
        }
    }
}

// Uppy ships its stylesheet precompiled. The application's theme imports the
// package's CSS from `vendor/`, where `node_modules/@uppy` does not exist, so
// a copy that matches the bundled scripts is kept in the package.
function copyUppyStyles() {
    const require = createRequire(import.meta.url)
    const { version } = require('@uppy/dashboard/package.json')
    const styles = readFileSync(
        require.resolve('@uppy/dashboard/css/style.min.css'),
        'utf8',
    ).replace(/^@charset "UTF-8";/, '')

    writeFileSync(
        'resources/css/uppy.css',
        `/* Generated by bin/build.js from @uppy/dashboard ${version}. Do not edit. */\n${styles}\n`,
    )
}

copyUppyStyles()
removeStaleChunks()

if (isDev) {
    const context = await esbuild.context(options)

    await context.watch()

    console.log(`Watching ${options.entryPoints['components/fluppy']}`)
} else {
    await esbuild.build(options)

    console.log(`Built ${outdir}`)
}
